function run(expr: string, base: string): string {
  try {
    return toIso(computeNextRunAt(expr, base))!
  } catch (err) {
    if (err instanceof ScheduledTaskSchemaError) return `!${err.message}`
    throw err
  }
}

describe('computeNextRunAt 与快照逐条一致', () => {
  it(`${PY_CASES.length} 条用例`, () => {
    const mismatches = PY_CASES.filter(([expr, base, expected]) => run(expr, base) !== expected).map(
      ([expr, base, expected]) => ({ expr, base, expected, actual: run(expr, base) }),
    )
    expect(mismatches).toEqual([])
  })

  it('日与周是 AND 语义：0 0 1 * 1 只在“1 号且周一”触发', () => {
    expect(run('0 0 1 * 1', '2026-09-24 00:00:00')).toBe('2027-02-01T00:00:00')
  })

  it('非字符串输入按 Python str(x or \'\') 处理', () => {
    expect(() => parseCronExpression(null)).toThrow('Cron 表达式不能为空')
    expect(() => parseCronExpression(0)).toThrow('Cron 表达式不能为空')
    expect(() => parseCronExpression(5)).toThrow('Cron 表达式格式错误，应为 5 段: 分 时 日 月 周')
    expect(() => parseCronExpression(['*', '*'])).toThrow('Cron 表达式格式错误，应为 5 段: 分 时 日 月 周')
  })
})
